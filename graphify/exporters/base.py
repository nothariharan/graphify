from __future__ import annotations

# Categorical palette for community coloring, shared by the HTML, SVG, and
# Obsidian exporters. Moved verbatim from graphify/export.py.
COMMUNITY_COLORS = [
    "#4E79A7", "#F28E2B", "#E15759", "#76B7B2", "#59A14F",
    "#EDC948", "#B07AA1", "#FF9DA7", "#9C755F", "#BAB0AC",
]

# The same ten hues, darkened for a light background. The palette above was designed
# for the dark one: on white, five of the ten colours fall below the 3:1 WCAG
# contrast ratio (yellow #EDC948 is 1.61:1, grey #BAB0AC 2.12:1, pink #FF9DA7 1.98:1),
# so half the communities disappear into the page. These are the same hues with the
# lightness walked down until every colour clears 4.6:1 on white - and they still
# clear 3.7:1 on the dark background, so the palette is safe in both themes.
# Generated by perf-lab/harness/light_palette.py; measured by light_contrast.py.
